    private val aliases: Map<String, String> = buildMap {
        for (group in groups) {
            val parts = group.split('|')
            val canonical = parts.first()
            for (alias in parts.drop(1)) put(alias, canonical)
        }
    }

    private fun normalize(value: String): String =
        java.text.Normalizer.normalize(value.lowercase(java.util.Locale.ROOT), java.text.Normalizer.Form.NFD)
            .replace(Regex("\\p{M}+"), "")
            .trim().replace(Regex("\\s+"), " ")

    fun terms(normalized: String): List<String> {
        val topic = normalize(normalized)
            .replace(Regex("^(peliculas?|series?|titulos?|cine) (de|sobre|con|acerca de|basad[oa]s? en) "), "")
            .replace(Regex("^(los|las|el|la|un|una|unos|unas) "), "")
            .trim()
        if (topic.length < 3) return emptyList()
        val direct = aliases[topic]
        val singular = if (direct == null) {
            val candidates = listOf(
                topic.removeSuffix("s"),
                topic.removeSuffix("es"),
                if (topic.endsWith("ces")) topic.dropLast(3) + "z" else topic,
            )
            candidates.firstNotNullOfOrNull { aliases[it] }
        } else null
        return listOfNotNull(direct ?: singular, topic).distinct()
    }
